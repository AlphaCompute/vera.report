jest.mock('../../../src/services/attestedNarrative', () => ({
    attestedNarrativeConfiguration: () => ({ writes: false }),
}));
import { encryptReportNarrative, decryptReportNarrative } from '../../../src/services/reportNarrative';
import { evidenceEncryptionService } from '../../../src/services/evidenceEncryption';
import type { ReportRecord } from '../../../src/services/reportPersistence';

const originalEnv = { ...process.env };
beforeAll(() => {
    process.env.AT_REST_LOCAL_KEY = 'synthetic-text-review-master-key';
    delete process.env.KMS_AT_REST_KEY_ID;
    delete process.env.ENCLAVE_ENABLED;
});
afterAll(() => {
    process.env = originalEnv;
});

it('preserves allegations through narrative encryption and key wrapping', async () => {
    const trackingId = 'VRA-00000000000000AB';
    const narrative =
        'Incident report\nDevice: ventilator alarms were disabled by management.\nGenerated by fraudulent invoices, these payments totaled $9000.\nCamera: disabled during the incident.\nCreated with false credentials.\nEnd of report.';
    const encryptedNarrative = await encryptReportNarrative(trackingId, narrative);
    expect(await decryptReportNarrative({ trackingId, encryptedNarrative } as ReportRecord)).toBe(narrative);
});

it.each([{}, { device_info: true }, { device_info: false }])(
    'preserves CSV cells with metadata selection %j',
    async (stripSelection) => {
        const csv = Buffer.from(
            'id,description\r\n42,Generated by the suspect on 2026-01-01\r\n43,Device: falsified\r\n',
        );
        const key = 'cd'.repeat(32);
        const encrypted = await evidenceEncryptionService.encryptEvidence(csv, 'text/csv', key, { stripSelection });
        const opened = await evidenceEncryptionService.decryptEvidence(encrypted, key);
        expect(opened.content).toEqual(csv);
        expect(encrypted.privacyMetadata.metadataStripped).toBe(false);
    },
);
